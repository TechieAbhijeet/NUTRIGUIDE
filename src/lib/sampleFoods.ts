import { FoodItem, RatingRule, FoodType } from '../types';

export function formatServingText(servingLabel: string, servingGrams?: number): string {
  if (!servingLabel) return servingGrams ? `${servingGrams}g` : '';
  // Avoid duplicating grams if already present in servingLabel
  if (/\b\d+\s*g\b/i.test(servingLabel) || /\(\d+g\)/i.test(servingLabel) || /\(\d+ml\)/i.test(servingLabel)) {
    return servingLabel;
  }
  return servingGrams ? `${servingLabel} (${servingGrams}g)` : servingLabel;
}

export function normalizeFoodType(rawType?: string, category?: string): FoodType {
  const t = rawType?.toLowerCase().trim();
  if (t === 'meal' || t === 'fruit' || t === 'vegetable' || t === 'grain' || t === 'pulse' || t === 'dairy' || t === 'snack' || t === 'drink') {
    return t as FoodType;
  }
  const cat = (category || '').toLowerCase();
  if (cat.includes('meal') || cat.includes('thali') || cat.includes('combo') || cat.includes('plate') || cat.includes('tiffin')) return 'meal';
  if (cat.includes('fruit')) return 'fruit';
  if (cat.includes('sabzi') || cat.includes('vegetable') || cat.includes('salad')) return 'vegetable';
  if (cat.includes('roti') || cat.includes('bread') || cat.includes('rice') || cat.includes('grain') || cat.includes('cereal') || cat.includes('khichdi')) return 'grain';
  if (cat.includes('dal') || cat.includes('pulse') || cat.includes('sambar') || cat.includes('chana') || cat.includes('rajma')) return 'pulse';
  if (cat.includes('dairy') || cat.includes('curd') || cat.includes('dahi') || cat.includes('paneer') || cat.includes('milk')) return 'dairy';
  if (cat.includes('beverage') || cat.includes('drink') || cat.includes('tea') || cat.includes('juice') || cat.includes('chai')) return 'drink';
  return 'snack';
}

export function getFoodIcon(food: { icon?: string; type?: FoodType; category?: string }): string {
  const custom = (food.icon || '').trim();
  if (custom) return custom;

  const foodType = food.type || normalizeFoodType(undefined, food.category);
  switch (foodType) {
    case 'meal':
      return '🍽️';
    case 'fruit':
      return '🍎';
    case 'vegetable':
      return '🥦';
    case 'grain':
      return '🌾';
    case 'pulse':
      return '🍲';
    case 'dairy':
      return '🥛';
    case 'drink':
      return '🍵';
    case 'snack':
    default:
      return '🍴';
  }
}

